SPACE_ADVANCE = 3


def build() -> None:
    glyphs = []
    for ch, rows in G.items():
        rows = rows + ["." * len(rows[0])] * (CELL_ROWS - len(rows))
        width = len(rows[0])
        assert all(len(r) == width for r in rows), f"ragged glyph {ch!r}"
        glyphs.append((ch, rows, width))

    cols = 16
    cell_w = 6
    atlas_w = cols * (cell_w + 1)
    atlas_rows = (len(glyphs) + cols - 1) // cols
    atlas_h = atlas_rows * (CELL_ROWS + 1)
    atlas = Image.new("RGBA", (atlas_w, atlas_h), (0, 0, 0, 0))

    lines = []
    for i, (ch, rows, width) in enumerate(glyphs):
        ax = (i % cols) * (cell_w + 1)
        ay = (i // cols) * (CELL_ROWS + 1)
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "#":
                    atlas.putpixel((ax + x, ay + y), (255, 255, 255, 255))
        lines.append(
            f"char id={ord(ch)} x={ax} y={ay} width={width} height={CELL_ROWS} "
            f"xoffset=0 yoffset={TOP_PAD} xadvance={width + 1} page=0 chnl=15"
        )
    lines.insert(0, f"char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 "
                    f"xadvance={SPACE_ADVANCE} page=0 chnl=15")

    out_dir = ROOT / "assets" / "fonts"
    out_dir.mkdir(parents=True, exist_ok=True)
    atlas.save(out_dir / "hearth_pixel.png")
    header = [
        f'info face="Hearth Pixel" size={FONT_SIZE} bold=0 italic=0 charset="" unicode=1 '
        f"stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0",
        f"common lineHeight={LINE_HEIGHT} base={TOP_PAD + CAP_ROWS} scaleW={atlas_w} "
        f"scaleH={atlas_h} pages=1 packed=0 alphaChnl=0 redChnl=0 greenChnl=0 blueChnl=0",
        'page id=0 file="hearth_pixel.png"',
        f"chars count={len(lines)}",
    ]
    (out_dir / "hearth_pixel.fnt").write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"font: {len(lines)} glyphs, atlas {atlas_w}x{atlas_h}")


if __name__ == "__main__":
    build()
